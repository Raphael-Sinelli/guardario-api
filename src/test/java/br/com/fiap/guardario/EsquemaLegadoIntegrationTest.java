package br.com.fiap.guardario;

import com.jayway.jsonpath.JsonPath;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.springframework.test.context.TestPropertySource;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

/**
 * O perfil prod cria o schema com ddl-auto: update, sem Flyway nem script. Este teste sobe o prod sobre um banco que
 * já tem a tabela usuario da versão anterior (sem versao e sem versao_token) e um usuário gravado, como o banco da VM:
 * as colunas novas entram com 0 nas linhas antigas, a tabela de junção das áreas seguidas nasce do zero, e o usuário
 * antigo continua entrando e trocando a senha.
 */
@ActiveProfiles("prod")
@TestPropertySource(properties = {
        "spring.datasource.username=sa",
        "spring.datasource.password=",
        "app.jwt.secret=chave-so-deste-teste-com-mais-de-32-caracteres",
        "app.admin.email=admin.legado@guardario.com",
        "app.admin.password=Senha-Admin-Legado-1"
})
class EsquemaLegadoIntegrationTest extends IntegracaoBase {

    private static final String URL = "jdbc:h2:mem:guardario-legado;DB_CLOSE_DELAY=-1";
    private static final String EMAIL = "legado@guardario.com";

    @Autowired
    private JdbcTemplate jdbc;

    // roda antes de o Spring subir: cria a tabela usuario como a versão anterior criava, com um usuário dentro
    @DynamicPropertySource
    static void bancoComATabelaAntiga(DynamicPropertyRegistry propriedades) {
        try (Connection conexao = DriverManager.getConnection(URL, "sa", "");
             Statement comando = conexao.createStatement()) {
            comando.execute("""
                    create table usuario (
                        id bigint generated by default as identity primary key,
                        nome varchar(120) not null,
                        email varchar(150) not null unique,
                        senha varchar(60) not null,
                        papel varchar(20) not null,
                        telefone varchar(20),
                        area_id bigint,
                        criado_em timestamp(6) with time zone not null
                    )""");
            comando.execute("insert into usuario (nome, email, senha, papel, criado_em) values ('Usuário Antigo', '" + EMAIL
                    + "', '" + new BCryptPasswordEncoder().encode("Senha-Antiga-1") + "', 'CIDADAO', current_timestamp)");
        } catch (SQLException e) {
            throw new IllegalStateException("Não deu para criar a tabela antiga", e);
        }
        propriedades.add("spring.datasource.url", () -> URL);
    }

    @Test
    void usuarioQueJaExistiaGanhaAVersaoZeroEContinuaTrocandoASenha() throws Exception {
        assertThat(jdbc.queryForObject("select versao from usuario where email = ?", Long.class, EMAIL)).isZero();
        assertThat(jdbc.queryForObject("select versao_token from usuario where email = ?", Integer.class, EMAIL)).isZero();

        String token = token(EMAIL, "Senha-Antiga-1");
        mockMvc.perform(put("/api/auth/senha").header(HttpHeaders.AUTHORIZATION, bearer(token))
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"senhaAtual\": \"Senha-Antiga-1\", \"novaSenha\": \"Senha-Nova-2\"}"))
                .andExpect(status().isNoContent());

        assertThat(jdbc.queryForObject("select versao from usuario where email = ?", Long.class, EMAIL)).isEqualTo(1L);
        assertThat(jdbc.queryForObject("select versao_token from usuario where email = ?", Integer.class, EMAIL)).isEqualTo(1);
        mockMvc.perform(get("/api/auth/me").header(HttpHeaders.AUTHORIZATION, bearer(token))).andExpect(status().isUnauthorized());
        token(EMAIL, "Senha-Nova-2");
    }

    // a tabela de junção do N:M (áreas seguidas) nasce na subida, com chave composta e as duas chaves estrangeiras,
    // e o usuário que já estava no banco continua lá
    @Test
    void tabelaDeJuncaoNasceComChaveCompostaSemMexerNoUsuarioAntigo() {
        assertThat(jdbc.queryForList("""
                select kcu.column_name from information_schema.table_constraints tc
                join information_schema.key_column_usage kcu
                  on kcu.constraint_name = tc.constraint_name and kcu.table_name = tc.table_name
                where tc.table_name = 'USUARIO_AREA_SEGUIDA' and tc.constraint_type = 'PRIMARY KEY'
                order by kcu.ordinal_position""", String.class)).containsExactlyInAnyOrder("USUARIO_ID", "AREA_ID");
        assertThat(jdbc.queryForObject("""
                select count(*) from information_schema.table_constraints
                where table_name = 'USUARIO_AREA_SEGUIDA' and constraint_type = 'FOREIGN KEY'""", Integer.class)).isEqualTo(2);
        assertThat(jdbc.queryForObject("select count(*) from usuario where email = ?", Integer.class, EMAIL)).isEqualTo(1);
    }

    // o usuário que já estava no banco segue uma área criada depois, e ela aparece na lista dele
    @Test
    void usuarioAntigoSegueUmaAreaNoProd() throws Exception {
        String area = mockMvc.perform(post("/api/areas").header(HttpHeaders.AUTHORIZATION, bearer(token("admin.legado@guardario.com", "Senha-Admin-Legado-1")))
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"nome\": \"Área do Banco Legado\", \"cidade\": \"São Paulo\", \"uf\": \"SP\", \"populacaoEstimada\": 100}"))
                .andExpect(status().isCreated()).andReturn().getResponse().getContentAsString();
        int areaId = JsonPath.read(area, "$.id");
        Long usuarioId = jdbc.queryForObject("select id from usuario where email = ?", Long.class, EMAIL);
        String senha = jdbc.queryForObject("select versao_token from usuario where email = ?", Integer.class, EMAIL) == 0
                ? "Senha-Antiga-1" : "Senha-Nova-2";
        String token = token(EMAIL, senha);

        mockMvc.perform(put("/api/auth/me/areas-seguidas/" + areaId).header(HttpHeaders.AUTHORIZATION, bearer(token)))
                .andExpect(status().isNoContent());
        mockMvc.perform(get("/api/auth/me/areas-seguidas").header(HttpHeaders.AUTHORIZATION, bearer(token)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$._embedded.areas[0].id").value(areaId));
        assertThat(jdbc.queryForObject("select count(*) from usuario_area_seguida where usuario_id = ?", Integer.class, usuarioId))
                .isEqualTo(1);
    }
}
